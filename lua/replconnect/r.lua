-- Part of replconnect-r; registered by `plugin/replconnect-r.lua`.
-- R in arf (https://github.com/eitsupi/arf): how to launch it with the
-- replconnect R package serving, and editor details.
--
-- arf embeds R, so the R session's pid is arf's pid. REPLConnect is started
-- from a generated user profile passed through `R_PROFILE_USER`; it first runs
-- the profile R would have run (`$R_PROFILE_USER`, else `./.Rprofile`, else
-- `~/.Rprofile`). The variable stays set, so arf's `:restart`/`:switch`
-- (which exec in place) start the service again.

local M = {
	name = "r",
	label = "R",
	filetypes = { "r", "rmd", "rnoweb" },
	prompt = "> ",
	trigger_characters = { "$", "@", ":", "[", '"', "(" },
	command = { "arf" },
	plot_capture = true,
	plots_hint = "run replconnect::capture_plots(TRUE) in R (needs the unigd package)",
	stop_hint = "run replconnect::shutdown() in R",
	startup_hint = "check R startup errors and the installed replconnect package version",
}

---Root of this plugin checkout (contains the `replconnect` R package).
---@return string
function M.root()
	local source = debug.getinfo(1, "S").source:sub(2)
	return vim.fs.dirname(vim.fs.dirname(vim.fs.dirname(source)))
end

---An R string literal for `s`.
---@param s string
---@return string
function M.r_string(s)
	return '"' .. s:gsub('[\\"]', "\\%0"):gsub("\n", "\\n") .. '"'
end

---R code for the generated user profile.
---@param root? string plugin checkout (contains `replconnect/`)
---@param opts? replconnect.ReplConfig
---@return string
function M.profile_code(root, opts)
	root = root or M.root()
	local capture, limit = require("replconnect.languages").plot_options(opts or {})
	local package = vim.fs.joinpath(root, "replconnect")
	local start = "replconnect::start()"
	if capture then
		-- Never prompt during startup: without unigd, say how to enable capture.
		start = start
			.. '; if (requireNamespace("unigd", quietly = TRUE)) replconnect::capture_plots(TRUE, limit = '
			.. string.format("%.0f", limit)
			.. ') else message("replconnect: plot capture needs unigd; run replconnect::capture_plots(TRUE) to install it")'
	end
	return table.concat({
		"# Generated by replconnect.nvim for :REPLStart; safe to delete.",
		"local({",
		'  profile <- Sys.getenv("REPLCONNECT_R_PROFILE_USER")',
		"  if (!nzchar(profile)) {",
		'    profile <- if (file.exists(".Rprofile")) ".Rprofile" else path.expand("~/.Rprofile")',
		"  }",
		"  if (file.exists(profile)) source(profile, local = globalenv())",
		"})",
		"if (interactive()) local({",
		'  if (requireNamespace("replconnect", quietly = TRUE)) {',
		"    " .. start,
		"  } else {",
		'    message("replconnect: the R package is not installed; install it with\\n",',
		'      "  install.packages(", '
			.. M.r_string(M.r_string(package))
			.. ', ", repos = NULL, type = \\"source\\")")',
		"  }",
		"})",
	}, "\n") .. "\n"
end

---The command line and environment: `command` and extra switches, with the
---generated profile written to a temporary file.
---@param opts replconnect.ReplConfig
---@param extra? string[] extra arf switches, e.g. `--with-r-version 4.4`
---@param root? string plugin checkout (default: this plugin)
---@param profile_path? string where to write the profile (default: a temp file)
---@return string[] cmd
---@return table<string, string> env
function M.build_cmd(opts, extra, root, profile_path)
	local code = M.profile_code(root or M.root(), opts)
	local cmd = vim.list_extend({}, opts.command)
	vim.list_extend(cmd, extra or {})
	profile_path = profile_path or (vim.fn.tempname() .. ".R")
	assert(
		vim.fn.writefile(vim.split(code, "\n", { plain = true }), profile_path) == 0,
		"cannot write the R profile " .. profile_path
	)
	return cmd,
		{
			R_PROFILE_USER = profile_path,
			REPLCONNECT_R_PROFILE_USER = vim.env.REPLCONNECT_R_PROFILE_USER or vim.env.R_PROFILE_USER or "",
		}
end

---Plugin options (lazy.nvim `opts`): the core's `repl` fields for R only,
---e.g. `{ command = { ... }, capture_plots = true }`. Optional: the plugin
---registers itself when loaded.
---@param opts? replconnect.ReplConfig
function M.setup(opts)
	require("replconnect.languages").configure(M, opts)
end

return M
